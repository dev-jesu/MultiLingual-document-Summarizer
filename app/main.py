from fastapi import FastAPI, Request, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.exceptions import RequestValidationError
from app.config import settings
from app.routers import upload, summarize

app = FastAPI(
    title=settings.APP_NAME,
    description="Scalable FastAPI backend for processing and summarizing Indian District Court legal documents.",
    version="2.0.0",
    docs_url="/docs",
    redoc_url="/redoc"
)

# Register routers
app.include_router(upload.router)
app.include_router(summarize.router)

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "http://localhost:5173",
        "http://127.0.0.1:5173"
    ],
    allow_credentials=True,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["*"],
)


@app.get("/", response_class=HTMLResponse, tags=["UI"])
async def root():
    """
    Return the single-page frontend application for document upload and summarization.
    """
    return HTMLResponse(
        """
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8" />
            <meta name="viewport" content="width=device-width, initial-scale=1.0" />
            <title>Legal Document Summarizer</title>
            <style>
                body { font-family: Arial, sans-serif; line-height: 1.5; margin: 0; padding: 0; background: #f5f7fb; color: #111; }
                .container { max-width: 900px; margin: 0 auto; padding: 24px; }
                h1 { margin-bottom: 8px; }
                .card { background: #ffffff; border-radius: 16px; box-shadow: 0 12px 32px rgba(15, 23, 42, 0.08); padding: 24px; margin-bottom: 24px; }
                .controls { display: grid; gap: 14px; }
                label { display: block; font-weight: 600; margin-bottom: 4px; }
                input[type=file], select, button { width: 100%; border: 1px solid #d1d5db; border-radius: 10px; padding: 12px 14px; font-size: 1rem; }
                button { background: #2563eb; color: white; font-weight: 700; cursor: pointer; transition: background 0.2s ease; }
                button:hover { background: #1d4ed8; }
                .output { white-space: pre-wrap; background: #f9fafb; border: 1px solid #e5e7eb; border-radius: 1rem; padding: 18px; margin-top: 18px; }
                .small { font-size: 0.9rem; color: #475569; }
                .hidden { display: none; }
            </style>
        </head>
        <body>
            <div class="container">
                <div class="card">
                    <h1>Legal Document Summarizer</h1>
                    <p class="small">Upload a PDF or DOCX legal document and get a concise summary generated by the backend.</p>
                    <div class="controls">
                        <label for="fileInput">Choose file</label>
                        <input id="fileInput" type="file" accept=".pdf,.docx" />
                        <label for="strategy">Chunking strategy</label>
                        <select id="strategy">
                            <option value="merged">Merged</option>
                            <option value="paragraph">Paragraph</option>
                            <option value="page">Page</option>
                        </select>
                        <label for="maxTokens">Max tokens per chunk</label>
                        <input id="maxTokens" type="number" value="6000" min="100" max="8000" />
                        <label for="overlap">Token overlap</label>
                        <input id="overlap" type="number" value="150" min="0" max="500" />
                        <button id="processButton">Process Document</button>
                        <button id="summarizeButton">Summarize Document</button>
                    </div>
                </div>

                <div class="card hidden" id="statusCard">
                    <h2>Result</h2>
                    <div id="statusMessage" class="small"></div>
                    <div id="resultOutput" class="output"></div>
                </div>
            </div>

            <script>
                const fileInput = document.getElementById('fileInput');
                const strategy = document.getElementById('strategy');
                const maxTokens = document.getElementById('maxTokens');
                const overlap = document.getElementById('overlap');
                const processButton = document.getElementById('processButton');
                const summarizeButton = document.getElementById('summarizeButton');
                const statusCard = document.getElementById('statusCard');
                const statusMessage = document.getElementById('statusMessage');
                const resultOutput = document.getElementById('resultOutput');

                const showResult = (title, payload) => {
                    statusCard.classList.remove('hidden');
                    statusMessage.textContent = title;
                    resultOutput.textContent = JSON.stringify(payload, null, 2);
                };

                const showError = (message) => {
                    statusCard.classList.remove('hidden');
                    statusMessage.textContent = message;
                    resultOutput.textContent = '';
                };

                const uploadFile = async (endpoint) => {
                    if (!fileInput.files.length) {
                        showError('Please choose a PDF or DOCX file first.');
                        return;
                    }

                    const selectedFile = fileInput.files[0];
                    const formData = new FormData();
                    formData.append('file', selectedFile);

                    if (endpoint === '/upload') {
                        formData.append('strategy', strategy.value);
                        formData.append('max_tokens', maxTokens.value);
                        formData.append('overlap', overlap.value);
                    }

                    statusMessage.textContent = 'Uploading and processing...';
                    resultOutput.textContent = '';
                    statusCard.classList.remove('hidden');

                    try {
                        const response = await fetch(endpoint, {
                            method: 'POST',
                            body: formData
                        });

                        if (!response.ok) {
                            const errorData = await response.json();
                            throw new Error(errorData.detail || 'Request failed.');
                        }

                        const data = await response.json();
                        const title = endpoint === '/upload' ? 'Document analysis completed' : 'Summarization completed';
                        showResult(title, data);
                    } catch (err) {
                        showError('Error: ' + err.message);
                    }
                };

                processButton.addEventListener('click', () => uploadFile('/upload'));
                summarizeButton.addEventListener('click', () => uploadFile('/summarize'));
            </script>
        </body>
        </html>
        """
    )


@app.exception_handler(RequestValidationError)
async def validation_exception_handler(request: Request, exc: RequestValidationError):
    """
    Custom exception handler for request validation errors to ensure clean JSON responses.
    """
    return JSONResponse(
        status_code=status.HTTP_400_BAD_REQUEST,
        content={"detail": f"Invalid request data: {exc.errors()}"}
    )
